/** 매핑에 없는 이름이 와도 화면에 한자가 새지 않도록 하는 최종 방어선 */
export function krStar(name: string): string {
  if (!name) return '';
  if (STARS_KR[name]) return STARS_KR[name];
  // 접두어 계열(운/유/월/일/시) 보정
  const prefix = name.slice(0, 1);
  const tail = name.slice(1);
  const prefixMap: Record<string, string> = {
    运: '운',
    流: '유',
    月: '월',
    日: '일',
    时: '시',
  };
  if (prefixMap[prefix] && STARS_KR[tail]) return prefixMap[prefix] + STARS_KR[tail];
  return '잡성';
}

