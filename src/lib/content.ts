export function minorLine(palace: PalaceView, tone: Tone = 'formal'): string {
  const table = tone === 'casual' ? MINOR_CASUAL : MINOR_MEANING;
  const notes = [...palace.minor, ...palace.adj]
    .map((s) => ({ star: s.name, text: table[s.name] }))
    .filter((x) => x.text)
    .slice(0, 2);
  if (!notes.length) return '';
  /* 2026-11-25 @kooleumi8 피드백 3번: 여러 별을 한 문단에 이어 붙이지 않고
     별마다 한 줄(줄바꿈)로 끊습니다. 화면은 '\n' 을 기준으로 줄을 나눠 그립니다. */
  return notes.map((n) => `${n.star} — ${n.text}`).join('\n');
}

/* --------------------------- 지수(指數) 계산 --------------------------- */

const GOOD_STARS = new Set(['좌보', '우필', '문창', '문곡', '천괴', '천월', '녹존', '천마']);
const HARD_STARS = new Set(['경양', '타라', '화성', '영성', '지공', '지겁', '겁살']);
const BRIGHT_SCORE: Record<string, number> = { 묘: 12, 왕: 9, 득: 5, 리: 1, 평: -2, 불: -6, 함: -11 };

export function palaceScore(palace: PalaceView | undefined): number {
  if (!palace) return 55;
  let score = 52;
  palace.major.forEach((s) => {
    score += BRIGHT_SCORE[s.brightness ?? '평'] ?? 0;
    if (s.mutagen === '화록') score += 9;
    if (s.mutagen === '화권') score += 6;
    if (s.mutagen === '화과') score += 5;
    if (s.mutagen === '화기') score -= 9;
  });
  if (!palace.major.length) score -= 6; // 공궁
  palace.minor.forEach((s) => {
    if (GOOD_STARS.has(s.name)) score += 5;
    if (HARD_STARS.has(s.name)) score -= 5;
    if (s.mutagen === '화록') score += 4;
    if (s.mutagen === '화기') score -= 5;
  });
  if (palace.adj.some((s) => ['홍란', '천희'].includes(s.name))) score += 3;
  if (palace.adj.some((s) => ['천곡', '천허', '고진', '과숙'].includes(s.name))) score -= 2;
  return Math.max(28, Math.min(96, Math.round(score)));
}

